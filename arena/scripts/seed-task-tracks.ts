function rubric(mode: ArenaMode, checks: string[]) {
  const rule = defaultRubric(mode);
  rule.dimensions.forEach((d, i) => {
    d.criteria += '\n本任务得分条件：' + checks[i];
  });
  return rule;
}
function open(id: string, condition: string, input: string, checks: string[], target?: string): ArenaTask {
  return {
    id,
    condition,
    input: synthetic + input,
    judge: rubric('open', checks),
    ...(target ? { target } : {}),
    meta: { synthetic: true, reviewed: '2026-09-13', difficulty: '进阶' },
  };
}
function multi(id: string, condition: string, input: string, rounds: [string, string][], checks: string[]): ArenaTask {
  return {
    id,
    condition,
    input: synthetic + input,
    rounds: rounds.map(([title, input], i) => ({ id: `r${i + 1}`, title, input })),
    judge: rubric('multi_turn', checks),
    meta: { synthetic: true, reviewed: '2026-09-13', difficulty: '进阶' },
  };
}
