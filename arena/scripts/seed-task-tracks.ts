export function seedBanks(): { def: ArenaDef; tasks: ArenaTask[] }[] {
  return (
    [
      ['practical-open', '实用场景 · 开放评审', 'open', openTasks],
      ['practical-multi', '实用场景 · 多轮任务', 'multi_turn', multiTasks],
    ] as const
  ).map(([name, title, mode, tasks]) => ({
    def: {
      name,
      title,
      mode,
      canary:
        mode === 'open' ? 'ququ-arena:f25d1626-54cd-43bd-8836-e8b012' : 'ququ-arena:4d7f1856-f4b2-4a9c-9361-d7e920',
      description:
        '使用明确标注的合成材料，覆盖核对、排期、预算、数据、需求变更与复盘。开放题允许不同合理答案；多轮任务含三轮固定材料与修订要求，个别任务需要识别不可满足的约束。',
      author: 'AI斗兽场 · 人工可编辑',
      version: '1.0.0',
      judge: defaultRubric(mode),
      conditions,
      review: {
        date: '2026-09-13',
        note: '逐题核对数字、资源与依赖、变更覆盖及评分条件；合成材料，语义评审仍可能存在裁判差异。',
      },
    },
    tasks,
  }));
}
export async function writeSeedBanks(root: string) {
  for (const { def, tasks } of seedBanks()) {
    validateQuestionBank(def, tasks);
    const dir = path.join(root, def.name);
    if (
      await access(dir).then(
        () => true,
        () => false,
      )
    )
      throw new Error(`${def.name} 已存在，保留用户题库，不覆盖`);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, 'arena.json'), JSON.stringify(def, null, 2) + '\n');
    await writeFile(path.join(dir, 'tasks.jsonl'), tasks.map((t) => JSON.stringify(t)).join('\n') + '\n');
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await writeSeedBanks(path.resolve('arenas'));
